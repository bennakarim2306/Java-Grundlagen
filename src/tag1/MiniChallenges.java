package tag1;

/**
 * Mini-Challenges fuer Tag 1
 *
 * Es wird NUR verwendet, was heute erklaert wurde:
 * Variablen, primitive Datentypen, String, Ausgabe, Kommentare.
 *
 * Jede Challenge hat eine feste Zielausgabe.
 * Erst ueberlegen, dann tippen, dann ausfuehren.
 */
public class MiniChallenges {
    public static void main(String[] args) {
        System.out.println("=== Mini-Challenges Tag 1 ===");
        System.out.println("Aufgaben stehen als Kommentar im Code.");

        // ---------------------------------------------------------------
        // CHALLENGE 1 - Steckbrief (ca. 5 Min.)
        // Ziel-Ausgabe:
        //   Name: Lea
        //   Alter: 20
        //   Stadt: Koeln
        // Regeln: 3 Variablen, 3 println-Zeilen.

        // CHALLENGE 2 - Eine Zeile (ca. 5 Min.)
        // Ziel-Ausgabe:
        //   Lea (20) aus Koeln
        // Regeln: genau EINE println-Zeile, Werte aus Variablen.

        // CHALLENGE 3 - Kassenbon (ca. 7 Min.)
        // Ziel-Ausgabe:
        //   Artikel: Kaffee
        //   Preis: 3.50 EUR
        // Regeln: double + printf mit %.2f

        // CHALLENGE 4 - Typen-Zoo (ca. 7 Min.)
        // Lege je eine Variable an: byte, int, double, char, boolean, String.
        // Gib alle in EINER Zeile getrennt durch " | " aus.

        // CHALLENGE 5 - Vorhersage (ca. 5 Min.)
        // Schreibe VORHER auf, was diese zwei Zeilen ausgeben,
        // dann Kommentarzeichen entfernen und pruefen:
        // System.out.println("Summe: " + 3 + 4);
        // System.out.println("Summe: " + (3 + 4));

        // CHALLENGE 6 - Tabelle (ca. 8 Min.)
        // Ziel-Ausgabe (mit \t ausrichten):
        //   Name	Alter
        //   Lea 	20
        //   Ben 	24

        // CHALLENGE 7 - Umbau (ca. 5 Min.)
        // Kopiere Challenge 1 und ersetze alle println durch print.
        // Sorge mit \n dafuer, dass die Ausgabe wieder gleich aussieht.

        // CHALLENGE 8 - Bonus (ca. 10 Min.)
        // Baue ein "Profil" mit 6 Zeilen Ausgabe, davon
        // mindestens eine mit printf und mindestens eine mit \t.
        // ---------------------------------------------------------------
    }
}

